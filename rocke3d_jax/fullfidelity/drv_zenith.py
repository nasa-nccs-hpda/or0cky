class CoszGrid:
    """GEOM_B.f RAD_COSZ0: cosz_init (SINJ, COSJ), COSZT, with LON(I) = DLON*(I-.5), SINIP/COSIP."""

    def __init__(self, use_imf=True):
        m = self.m = _libm(use_imf)
        sin, cos = m['sin'], m['cos']
        dlat = (180.0 / 45.0) * RADIAN        # DLAT_DG = 180./REAL(JM-1) (REAL*4 expression, exactly 4.0); radian = pi/180
        dlon = TWOPI * (1.0 / 72.0)
        self.lon = np.array([dlon * (i - 0.5) for i in range(1, IM + 1)])
        self.sinip = np.array([sin(x) for x in self.lon])
        self.cosip = np.array([cos(x) for x in self.lon])
        sinj = np.zeros(JM + 1)
        cosj = np.zeros(JM + 1)
        phis, sphis, cphis = -0.25 * TWOPI, -1.0, 0.0
        for j in range(1, JM):                      # J_0 .. J_1S = 1 .. JM-1
            phin = dlat * (j - 0.5 * JM)
            sphin, cphin = sin(phin), cos(phin)
            phim = (phin * sphin + cphin - phis * sphis - cphis) / (sphin - sphis)
            sinj[j], cosj[j] = sin(phim), cos(phim)
            phis, sphis, cphis = phin, sphin, cphin
        phin, sphin, cphin = 0.25 * TWOPI, 1.0, 0.0
        phim = (phin * sphin + cphin - phis * sphis - cphis) / (sphin - sphis)
        sinj[JM], cosj[JM] = sin(phim), cos(phim)
        self.sinj, self.cosj = sinj, cosj

    def coszt(self, rot1, rot2, sind, cosd):
        """COSZT(rot1, rot2, cosz): time-weighted cosz, array (IM, JM); polar boxes: column I=1 only (others stay 0)."""
        m = self.m
        sin, cos, acos, sqrt = m['sin'], m['cos'], m['acos'], m['sqrt']
        zero1 = 1.0e-2
        drot = rot2 - rot1
        sr1, cr1, sr2, cr2 = sin(rot1), cos(rot1), sin(rot2), cos(rot2)
        lt1 = rot1 + self.lon
        lt2 = rot2 + self.lon
        slt1 = sr1 * self.cosip + cr1 * self.sinip
        slt2 = sr2 * self.cosip + cr2 * self.sinip
        cz = np.zeros((IM, JM + 1))
        for j in (1, JM):                            # polar boxes
            sjsd = self.sinj[j] * sind
            cjcd = self.cosj[j] * cosd
            if sjsd + cjcd > zero1:
                if sjsd - cjcd < 0.0:
                    dusk = acos(-sjsd / cjcd)
                    sdusk = sqrt(cjcd * cjcd - sjsd * sjsd) / cjcd
                    dawn, sdawn = -dusk, -sdusk
                    cz[0, j] = (sjsd * (dusk - dawn) + cjcd * (sdusk - sdawn)) / TWOPI
                else:
                    cz[0, j] = sjsd
            else:
                cz[0, j] = 0.0
        for j in range(2, JM):                       # J_0S .. J_1S
            sjsd = self.sinj[j] * sind
            cjcd = self.cosj[j] * cosd
            if sjsd + cjcd > zero1:
                if sjsd - cjcd < 0.0:
                    dusk = acos(-sjsd / cjcd)
                    sdusk = sqrt(cjcd * cjcd - sjsd * sjsd) / cjcd
                    dawn, sdawn = -dusk, -sdusk
                    zero2 = zero1 / cjcd
                    for i in range(IM):
                        if not (dusk > lt1[i] + zero2):
                            dusk = dusk + TWOPI
                            dawn = dawn + TWOPI
                        if not (dawn < lt2[i] - zero2):
                            cz[i, j] = 0.0
                            continue
                        if dawn >= lt1[i]:
                            if dusk < lt2[i]:
                                cz[i, j] = (sjsd * (dusk - dawn) + cjcd * (sdusk - sdawn)) / drot
                            else:
                                cz[i, j] = (sjsd * (lt2[i] - dawn) + cjcd * (slt2[i] - sdawn)) / drot
                            continue
                        if dusk >= lt2[i]:
                            cz[i, j] = sjsd + cjcd * (slt2[i] - slt1[i]) / drot
                            continue
                        if not (dawn + TWOPI < lt2[i] - zero2):
                            cz[i, j] = (sjsd * (dusk - lt1[i]) + cjcd * (sdusk - slt1[i])) / drot
                        else:
                            cz[i, j] = (sjsd * (lt2[i] - dawn - TWOPI + dusk - lt1[i]) + cjcd * (slt2[i] - sdawn + sdusk - slt1[i])) / drot
                else:
                    for i in range(IM):
                        cz[i, j] = sjsd + cjcd * (slt2[i] - slt1[i]) / drot
            else:
                cz[:, j] = 0.0
        return cz[:, 1:]


class Zenith:
    """cosz1(itime) for the dumps' model: orbit parameters of 1850, noon-of-day declination, DTsrc = 1800 s."""

    def __init__(self, year=1850.0, use_imf=True, iyear1=IYEAR1):
        self.orbit = EarthOrbit(year, use_imf)
        self.grid = CoszGrid(use_imf)
        self.iyear1 = iyear1
        self._daily = {}

    def daily(self, t):
        """DAILY_orbit: sinD, cosD at noon of the day containing t."""
        day0 = (t // SECONDS_PER_DAY) * SECONDS_PER_DAY
        if day0 not in self._daily:
            tn = Fraction(day0) + Fraction(SECONDS_PER_DAY, 2)
            sind = self.orbit.sin_declination(tn)
            self._daily[day0] = (sind, self.orbit.m['sqrt'](1.0 - sind ** 2))
        return self._daily[day0]

    def cosz1(self, itime, t=None):
        """CALC_ZENITH_ANGLE(modelEclock, 1, cosz1) for the clock reading `itime` (or an explicit time t)."""
        t1 = time_of_itime(itime, self.iyear1) if t is None else t
        sind, cosd = self.daily(t1)
        rot1 = self.orbit.hour_angle(t1)
        rot2 = self.orbit.hour_angle(t1 + DTSRC)
        drot = rot2 - rot1
        drot = -PI + _mod(drot + PI, 2.0 * PI)
        if abs(drot) > PI / 4:
            raise RuntimeError("Time step is too large for accurate radiation.")
        if drot < 0:
            rot2 = rot1
            rot1 = rot1 + drot
        elif drot > 0:
            rot2 = rot1 + drot
        else:
            rot2 = rot2 + 1.0e-10
        return self.grid.coszt(rot1, rot2, sind, cosd)
