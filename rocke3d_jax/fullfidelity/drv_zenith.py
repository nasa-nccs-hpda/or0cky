# ---------------------------------------------------------------------------------------------- orbpar (shared/orbpar.f)
def orbpar(year, use_imf=True):
    """Berger orbital parameters: (eccentricity, obliquity [deg], longitude of perihelion [deg])."""
    m = _libm(use_imf)
    sin, cos, atan2, sqrt = m['sin'], m['cos'], m['atan2'], m['sqrt']
    ym = year - 1950.0
    sumc = 0.0
    for a, b, c in TABL1:
        arg = RADIAN * (ym * b / 3600.0 + c)
        sumc = sumc + a * cos(arg)
    oblq = 23.320556 + sumc / 3600.0
    es = ec = 0.0
    for a, b, c in TABL4:
        arg = RADIAN * (ym * b / 3600.0 + c)
        es = es + a * sin(arg)
        ec = ec + a * cos(arg)
    eccen = sqrt(es * es + ec * ec)
    pie = atan2(es, ec)
    f = 0.0
    for a, b, c in TABL5:
        arg = RADIAN * (ym * b / 3600.0 + c)
        f = f + a * sin(arg)
    psi = RADIAN * (3.392506 + (ym * 50.439273 + f) / 3600.0)
    om = _mod(pie + psi + 0.5 * TWOPI, TWOPI)
    if om < 0.0:
        om = om + TWOPI
    return eccen, oblq, om / RADIAN


# ---------------------------------------------------------------------------------------------- Rational helpers
def rational_from_real(x, tol):
    """shared/Rational.F90 newRational_real_dp: continued fraction to within `tol`; returns an exact Fraction."""
    absx = abs(x)
    w = int(math.floor(absx))
    xx = absx - w
    p2, q2 = 1, 0
    p1, q1 = 0, 1
    pn, qn = 0, 1
    while xx != 0.0:
        xx = 1.0 / xx
        a = int(math.floor(xx))
        xx = xx - a
        pn = a * p1 + p2
        qn = a * q1 + q2
        p2, q2 = p1, q1
        p1, q1 = pn, qn
        if abs(qn * (absx - w) - pn) < qn * tol:
            break
    r = Fraction(w) + Fraction(pn, qn)
    return -r if x < 0 else r


def rat_real(f):
    """Rational%toReal: real(numerator)/real(denominator) + whole (whole and numerator carry the sign of the rational)."""
    whole = int(f)            # truncation toward zero
    rem = f - whole
    return float(rem.numerator) / float(rem.denominator) + float(whole)


class EarthOrbit:
    """Earth365DayOrbit for orbpar(year) parameters (see module docstring)."""

    def __init__(self, year=1850.0, use_imf=True):
        self.m = _libm(use_imf)
        self.ecc, self.obl, self.omegvp = orbpar(year, use_imf)
        self.prot = Fraction(SECONDS_PER_DAY * 365, 366)
        self.porb = Fraction(SECONDS_PER_YEAR)
        # julian calendar year 1, month 3, date 21, hour 12: 59 days elapsed before Mar 1 + 20
        self.t_ve = Fraction((59 + 20) * SECONDS_PER_DAY + 12 * 3600)
        m = self.m
        ta = -self.omegvp * RADIAN
        ma = self._mean_from_true(ta)
        self.t_peri = self.t_ve - rational_from_real(ma / TWOPI * float(self.porb), 1.0e-3)

    def _mean_from_true(self, nu):
        m, e = self.m, self.ecc
        ea = 2.0 * m['atan'](m['sqrt']((1.0 - e) / (1.0 + e)) * m['tan'](nu / 2.0))
        return ea - e * m['sin'](ea)

    def mean_anomaly(self, t):
        f = (t % self.porb) - (self.t_peri % self.porb)
        f = f / self.porb
        return rat_real(f) * TWOPI

    def true_anomaly(self, t):
        m, e = self.m, self.ecc
        ma = self.mean_anomaly(t)
        x = ma + e * (m['sin'](ma) + e * m['sin'](2.0 * ma) / 2.0)
        while True:
            f = x - e * m['sin'](x) - ma
            df = 1.0 - e * m['cos'](x)
            dx = -f / df
            x = x + dx
            if abs(dx) < 1.0e-10:
                break
        return _mod(2.0 * m['atan'](m['sqrt']((1.0 + e) / (1.0 - e)) * m['tan'](x / 2.0)), TWOPI)

    def sin_declination(self, t):
        m = self.m
        nu = self.true_anomaly(t)
        delta = nu + self.omegvp * RADIAN
        return m['sin'](self.obl * RADIAN) * m['sin'](delta)

    def hour_angle(self, t):
        """AbstractOrbit.getHourAngle with EOT = 'F' and hourAngleOffset = 0."""
        f1 = t / self.prot
        f2 = t / self.porb
        d = f1 - f2
        fr = d - (d.numerator // d.denominator)       # Rational fraction(): value in [0, 1)
        return _mod(TWOPI * rat_real(fr) - 0.0, TWOPI)


def time_of_itime(itime, iyear1=IYEAR1):
    """BaseTime (seconds since 0001-01-01 00:00 in the 365-day calendar) of the model clock at `itime` (MODELE.f:1315-1320)."""
    return Fraction((iyear1 - 1) * SECONDS_PER_YEAR + DTSRC * itime)


