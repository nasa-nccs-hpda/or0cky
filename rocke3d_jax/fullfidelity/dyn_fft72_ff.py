def _tables():
    """FFT0 (FFT72.f 31-57), keeping the sequential-overwrite semantics: at N=KM/4 several
    assignments hit the same index (C(KM/4), S(0), S(KM/2), C(3*KM/4), S(KM)), and each statement
    reads the C(N) left by the previous one."""
    C = {}
    S = {}
    for N in range(0, KM // 4 + 1):
        C[N] = np.cos(TWOPI * N / float(KM))
        S[KM // 4 - N] = C[N]
        C[KM // 2 - N] = -C[N]
        S[KM // 4 + N] = C[N]
        C[KM // 2 + N] = -C[N]
        S[3 * KM // 4 - N] = -C[N]
        C[KM - N] = C[N]
        S[3 * KM // 4 + N] = -C[N]
    return C, S


