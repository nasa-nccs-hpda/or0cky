def fft_rows(x):
    """x: array (KM, nrows) -> (A, B) arrays (KM/2+1, nrows)."""
    A, B = fft({k + 1: x[k] for k in range(KM)})
    sh = x.shape[1:]
    return (np.array([np.broadcast_to(A[n], sh) for n in range(KM // 2 + 1)]),
            np.array([np.broadcast_to(B[n], sh) for n in range(KM // 2 + 1)]))


def ffti_rows(A, B):
    """A, B: arrays (KM/2+1, nrows) -> x (KM, nrows)."""
    F = ffti({n: A[n] for n in range(KM // 2 + 1)}, {n: B[n] for n in range(KM // 2 + 1)})
    sh = A.shape[1:]
    return np.array([np.broadcast_to(F[k + 1], sh) for k in range(KM)])
